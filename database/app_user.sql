-- Only needed if you use Supabase (SQLite creates this table automatically).
-- Run in the Supabase SQL Editor.
CREATE TABLE public.app_user (
    user_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name      character varying(100) NOT NULL,
    email          character varying(150) NOT NULL UNIQUE,
    password_hash  character varying(255) NOT NULL,
    role           character varying(30) NOT NULL DEFAULT 'staff',
    created_at     timestamptz NOT NULL DEFAULT NOW()
);

ALTER TABLE public.app_user ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow public read access" ON public.app_user FOR SELECT USING (true);
CREATE POLICY "Allow public insert" ON public.app_user FOR INSERT WITH CHECK (true);